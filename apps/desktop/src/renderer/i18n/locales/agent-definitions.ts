export type AgentDefinitionLocale = keyof typeof agentDefinitionMessages;

export function withAgentDefinitionMessages<T extends { agents: object }>(
  locale: AgentDefinitionLocale,
  messages: T,
): T & {
  agents: T["agents"] & (typeof agentDefinitionMessages)[AgentDefinitionLocale];
} {
  return {
    ...messages,
    agents: {
      ...messages.agents,
      ...agentDefinitionMessages[locale],
    },
  };
}
