export type AgentDeepSeekHarnessLocale =
  keyof typeof agentDeepSeekHarnessMessages;

export function withAgentDeepSeekHarnessMessages<T extends { agents: object }>(
  locale: AgentDeepSeekHarnessLocale,
  messages: T,
): T & {
  agents: T["agents"] &
    (typeof agentDeepSeekHarnessMessages)[AgentDeepSeekHarnessLocale];
} {
  return {
    ...messages,
    agents: {
      ...messages.agents,
      ...agentDeepSeekHarnessMessages[locale],
    },
  };
}
